    উত্তর: "অবজেক্ট লিটারেল হলো একটি একক অবজেক্ট তৈরির সহজ উপায়। কিন্তু ক্লাস ব্যবহার করি তখন, যখন আমাদের একই ধরণের অনেকগুলো অবজেক্ট তৈরি করতে হয় এবং সেই অবজেক্টগুলোতে নির্দিষ্ট কিছু মেথড বা আচরণ (behavior) যুক্ত রাখতে হয়। ক্লাস আমাদের কোডকে আরও সুশৃঙ্খল ও মডুলার করে।"
