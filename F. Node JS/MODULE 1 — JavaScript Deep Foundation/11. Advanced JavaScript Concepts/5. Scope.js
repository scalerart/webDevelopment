    উত্তর: "জাভাস্ক্রিপ্ট সবসময় নিকটবর্তী স্কোপকে অগ্রাধিকার দেয়। অর্থাৎ সে ইনার স্কোপের ভেরিয়েবলটিই নেবে এবং আউটার স্কোপেরটিকে ওভাররাইড করবে (Shadowing)।"
