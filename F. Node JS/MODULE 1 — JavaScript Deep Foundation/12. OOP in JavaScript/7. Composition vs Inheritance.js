    উত্তর: "যদি অবজেক্টগুলোর মধ্যে একটি স্পষ্ট এবং প্রাকৃতিক 'Is-a' সম্পর্ক থাকে এবং এটি ভবিষ্যতে খুব একটা পরিবর্তন হওয়ার সম্ভাবনা না থাকে, তবেই ইনহেরিটেন্স ব্যবহার করা যেতে পারে। অন্যথায়, কম্পোজিশনই নিরাপদ এবং আধুনিক পছন্দ।"
