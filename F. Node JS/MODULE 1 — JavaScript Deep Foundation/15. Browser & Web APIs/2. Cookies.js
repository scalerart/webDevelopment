    উত্তর: "LocalStorage জাভাস্ক্রিপ্ট দিয়ে সহজেই অ্যাক্সেস করা যায়, তাই XSS আক্রমণের সময় হ্যাকার সহজেই আপনার টোকেন চুরি করতে পারে। কিন্তু যদি টোকেনটি HttpOnly কুকিতে রাখা হয়, তবে ব্রাউজার তা জাভাস্ক্রিপ্টকে পড়তে দেয় না। ফলে হ্যাকার স্ক্রিপ্ট ইনজেক্ট করলেও আপনার টোকেন চুরি করতে পারবে না। এজন্যই কুকি অনেক বেশি নিরাপদ।"
