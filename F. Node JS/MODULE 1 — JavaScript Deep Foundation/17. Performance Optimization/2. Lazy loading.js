    উত্তর: "ইউজার যদি কোনো Placeholder না দেখে, তবে সেটি খারাপ ইউজার এক্সপেরিয়েন্স। এজন্য 'Blur-up' টেকনিক বা লোডিং স্পিনার ব্যবহার করা উচিত। এছাড়া, 'Intersection Observer' ব্যবহার করার সময় আমরা ইমেজ ট্যাগেই src ফাঁকা রেখে data-src-এ আসল ইউআরএল রাখি, এবং ছবি স্ক্রিনে আসার ঠিক আগে data-src থেকে src-এ ডাটা সেট করে দিই। এতে ব্রাউজার ইমেজটি দ্রুত রেন্ডার করতে পারে।"
