/*

Key Points
১.  map বনাম forEach
    ইন্টারভিউয়ার প্রায়ই জিজ্ঞেস করে— map এবং forEach এর মধ্যে পার্থক্য কী?

    উত্তর: map একটি নতুন অ্যারে রিটার্ন করে, তাই এটি চেইনিং (chaining) করা যায়। অন্যদিকে, forEach শুধু লুপ চালায় এবং undefined রিটার্ন করে। ডেটা ট্রান্সফরমেশনের জন্য map বেটার।

২.  find বনাম filter
    উত্তর: filter সবসময় একটি নতুন অ্যারে রিটার্ন করে (এমনকি যদি একটি এলিমেন্টও পায়)। অন্যদিকে find সরাসরি ওই এলিমেন্টটি রিটার্ন করে। পারফরম্যান্সের দিক থেকে, যদি আমরা জানি যে একটি ইউনিক আইডি দিয়ে একটি আইটেম খুঁজছি, তবে find ব্যবহার করা বুদ্ধিমানের কাজ কারণ এটি কাঙ্ক্ষিত আইটেমটি পাওয়ার সাথে সাথেই লুপ বন্ধ করে দেয়।

৩.  reduce এর শক্তি
    উত্তর: reduce সবচেয়ে পাওয়ারফুল কারণ এটি দিয়ে map, filter এমনকি find-এর কাজও করা সম্ভব। এটি অ্যারে থেকে শুধু অ্যারে নয়, অবজেক্ট, কাউন্টার বা ক্যালকুলেশন—যেকোনো কিছু তৈরি করতে পারে।

৪.  প্র্যাকটিস চ্যালেঞ্জ (ইন্টারভিউ স্টাইলে)
    আপনার দক্ষতা ঝালাই করার জন্য এই ছোট কোডটি দেখুন এবং আউটপুট কী হবে তা চিন্তা করুন:
    JavaScript
        const items = [10, 20, 30, 40];

        const result = items
        .map(x => x * 2)             // [20, 40, 60, 80]
        .filter(x => x > 50)         // [60, 80]
        .reduce((acc, curr) => acc + curr, 0); // 140

        console.log(result);

    এই চেইনিং লজিকটি বুঝতে পারা মানে আপনি অ্যারে মেথডগুলো দিয়ে ডেটা ম্যানিপুলেশনে বেশ দক্ষ।
*/