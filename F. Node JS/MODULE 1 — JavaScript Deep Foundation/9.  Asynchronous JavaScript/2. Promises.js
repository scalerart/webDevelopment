    উত্তর: "কলব্যাক হলো একটি ফাংশন যা পরে রান করা হয়, যা বড় কোডে 'Callback Hell' তৈরি করে। অন্যদিকে, Promise হলো একটি অবজেক্ট যা অসিঙ্ক্রোনাস কাজের ফলাফল ধরে রাখে এবং .then() ও .catch() মেথড ব্যবহার করে কোডকে অনেক ক্লিন ও হ্যান্ডেল করা সহজ করে তোলে।"
